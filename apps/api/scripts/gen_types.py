"""Generate packages/api-types/src/index.ts from the API's OpenAPI schema.

    python -m scripts.gen_types            # write the file
    python -m scripts.gen_types --check    # exit 1 if the file is stale (CI)

No running server or Node needed: the schema comes straight from the FastAPI app.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from typing import Any

os.environ.setdefault("DATABASE_URL", "postgresql+asyncpg://unused:unused@localhost/unused")
os.environ.setdefault("JWT_SECRET", "typegen-" + "x" * 40)

from app.core import constants  # noqa: E402
from app.core.config import get_settings  # noqa: E402
from app.main import create_app  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "packages" / "api-types" / "src" / "index.ts"
PAGE = re.compile(r"^Page_(.+)_$")
SKIP = re.compile(r"^(HTTPValidationError|ValidationError)$")


def ts_name(name: str) -> str:
    m = PAGE.match(name)
    if m:
        return f"Page<{ts_name(m.group(1))}>"
    return re.sub(r"-(Input|Output)$", "", name)


def ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return ts_name(s["$ref"].rsplit("/", 1)[-1])
    if "const" in s:
        return repr(s["const"]).replace("'", '"')
    if "enum" in s:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts: list[str] = []
            for sub in s[key]:
                part = ts_type(sub)
                if part not in parts:
                    parts.append(part)
            return " | ".join(parts)
    t = s.get("type")
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if t == "object" or (t is None and "additionalProperties" in s):
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap)}>"
        if s.get("properties"):
            props = ", ".join(f"{k}: {ts_type(v)}" for k, v in s["properties"].items())
            return "{ " + props + " }"
        return "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(t or "", "unknown")


def interface(name: str, schema: dict[str, Any]) -> str:
    lines = []
    if schema.get("description"):
        lines.append(f"/** {schema['description'].strip()} */")
    if "properties" not in schema:
        return "\n".join(lines + [f"export type {ts_name(name)} = {ts_type(schema)};"])
    required = set(schema.get("required", []))
    lines.append(f"export interface {ts_name(name)} {{")
    for prop, ps in schema["properties"].items():
        opt = "" if prop in required else "?"
        lines.append(f"  {prop}{opt}: {ts_type(ps)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    spec = create_app(get_settings()).openapi()
    schemas: dict[str, Any] = spec["components"]["schemas"]
    seen: set[str] = set()
    blocks = [
        "/* eslint-disable */",
        "// AUTO-GENERATED by apps/api/scripts/gen_types.py from the API's OpenAPI schema.",
        "// Do not edit by hand: run `make types` (or `python -m scripts.gen_types` in apps/api).",
        "",
        "export interface Page<T> {\n  items: T[];\n  total: number;\n  page: number;\n  size: number;\n}",
    ]
    for name in sorted(schemas, key=lambda n: ts_name(n).lower()):
        if PAGE.match(name) or SKIP.match(name) or name.startswith("Body_"):
            continue
        tn = ts_name(name)
        if tn in seen:
            continue
        seen.add(tn)
        blocks.append(interface(name, schemas[name]))

    def const(n: str, values: tuple[str, ...]) -> str:
        return (
            f"export const {n} = [{', '.join(repr(v).replace(chr(39), chr(34)) for v in values)}] as const;"
        )

    blocks += [
        const("CONCENTRATIONS", constants.CONCENTRATIONS),
        const("GENDERS", constants.GENDERS),
        const("SILLAGES", constants.SILLAGES),
        const("NOTE_POSITIONS", constants.NOTE_POSITIONS),
        const("COLLECTION_STATUSES", constants.COLLECTION_STATUSES),
        const("BOTTLE_TYPES", constants.BOTTLE_TYPES),
        const("PICK_OCCASIONS", constants.PICK_OCCASIONS),
        const("RADAR_AXES", constants.RADAR_AXES),
        const("GENDER_PREFERENCES", constants.GENDER_PREFERENCES),
        "",
        "export type CollectionStatus = (typeof COLLECTION_STATUSES)[number];",
        "export type BottleType = (typeof BOTTLE_TYPES)[number];",
        "export type PickOccasion = (typeof PICK_OCCASIONS)[number];",
        "export type Concentration = (typeof CONCENTRATIONS)[number];",
        "export type Gender = (typeof GENDERS)[number];",
        "export type RadarAxis = (typeof RADAR_AXES)[number];",
        "export type GenderPreference = (typeof GENDER_PREFERENCES)[number];",
        f"export const ML_PER_SPRAY = {get_settings().ML_PER_SPRAY};",
    ]
    return "\n\n".join(blocks).replace("\n\n\n", "\n\n") + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    text = render()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is stale — run `make types`", file=sys.stderr)
            sys.exit(1)
        print("api-types up to date")
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Wrote {args.out} ({text.count('export ')} exports)")


if __name__ == "__main__":
    main()
